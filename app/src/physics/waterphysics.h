
#pragma once

/*
 * * Water Physics - Buoyancy, Ballast & Vertical & Forward Movement
 */

class WaterPhysics
{
  public:
    //! Vertical movement
    // Maximal vertical speed in m/s
    double maxVerticalSpeed = 5.0;

    // Maximal vertical acceleration in m/s²
    double verticalAcceleration = 3.0;

    // Time required to reach full acceleration in seconds
    double accelerationRampTime = 2.0;

    //! Water Resistance
    // Linear Drag - slows down movement proportional to velocity
    double linearDrag = 0.25;

    // Quadratic Drag - increases resistance at higher velocities
    double quadraticDrag = 0.08;

    //! Forward Movement
    // No speed limit: terminal velocity emerges where thrust equals drag
    // Forward thrust in m/s² (results in ~12 m/s)
    double forwardThrust = 6.96;

    // Reverse thrust in m/s² (results in ~7.5 m/s)
    double reverseThrust = 3;

    // Linear drag along the nose - lower than vertical (streamlined hull)
    double forwardLinearDrag = 0.1;

    // Quadratic drag along the nose - dominates at higher velocities
    double forwardQuadraticDrag = 0.04;

    //! Buoyancy & Ballast
    // Acceleration generated by buoyancy (m/s²)
    double buoyancyAcceleration = 5.0;

    // Speed of filling or emptying the ballast tank (% per second)
    double ballastChangeRate = 25.0;

    // Time constant for buoyancy response (seconds)
    double buoyancyResponseTime = 1.5;

    //! Water Drift

    // Strength of subtle vertical movement at neutral buoyancy (m/s)
    double waterDriftStrength = 0.08;

    // Frequency factor of the vertical water drift (rad/s)
    double waterDriftFrequency = 0.8;

    //! Ballast Control
    // Set ballast water level directly (0-100%)
    void setWaterLevel(double percentage);

    // Increase or decrease ballast water level based on input and delta time
    void changeWaterLevel(double input, double dt);

    //! Physics Update & Getters
    // Calculate vertical displacement based on buoyancy, thrust and drag
    double updateVertical(double input, double dt);

    // Return current ballast water level (0-100%)
    double getWaterLevel() const;

    // Return current vertical velocity (m/s)
    double getVerticalVelocity() const;

    // Calculate displacement along the nose based on thrust and drag
    double updateForward(double input, double dt);

    // Return current forward velocity (m/s)
    double getForwardVelocity() const;

  private:
    //! Ballast State
    // Current ballast water level (50% = neutral buoyancy)
    double waterLevel = 50.0;
    double currentBuoyancy = 0.0;

    //! Vertical Movement State
    // Current vertical velocity (positive = ascending, negative = descending)
    double verticalVelocity = 0.0;

    // Progress of acceleration ramp (0.0 to 1.0)
    double accelerationProgress = 0.0;

    // Previous input direction, used to reset acceleration ramp
    double previousDirection = 0.0;

    //! Forward Movement State
    // Current forward velocity (positive = forward, negative = backward)
    double forwardVelocity = 0.0;

    //! Simulation Time Tracking
    // Accumulated simulation time for water drift calculations
    double elapsedTime = 0.0;
};
